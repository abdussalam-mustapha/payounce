// Copies compiled ABIs into the web app as typed `as const` exports.
import { readFileSync, writeFileSync } from "node:fs";

const names = [
  ["PayounceFactory", "PayounceFactory.sol"],
  ["PayounceCircle", "PayounceCircle.sol"],
  ["PayounceReputation", "PayounceReputation.sol"],
  ["MockV3Aggregator", "mocks/MockV3Aggregator.sol"],
];
let out = "// Generated by contracts/scripts/export-abi.mjs — do not edit.\n\n";
for (const [n, file] of names) {
  const { abi } = JSON.parse(readFileSync(`artifacts/contracts/${file}/${n}.json`, "utf8"));
  const id = n[0].toLowerCase() + n.slice(1) + "Abi";
  out += `export const ${id} = ${JSON.stringify(abi, null, 2)} as const;\n\n`;
}
writeFileSync("../web/src/lib/abi.ts", out);
console.log("wrote web/src/lib/abi.ts");
